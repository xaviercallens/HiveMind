#!/usr/bin/env python3
"""Render the planetary-scale plan and the parked list from docs/roadmap/planetary_streams.json.

The JSON manifest is the single source of truth; the two markdown files are generated and checked in, and
tests/test_planetary_streams.py fails when they drift. Also renders one GitHub issue body per stream.

Usage:
  python3 scripts/render_planetary_plan.py                 # write docs/roadmap/PLANETARY_SCALE_PLAN.md and PARKED.md
  python3 scripts/render_planetary_plan.py --check         # exit 1 if the checked-in files differ from a fresh render
  python3 scripts/render_planetary_plan.py --issue PS-01   # print the issue body for one stream
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs" / "roadmap" / "planetary_streams.json"
PLAN_MD = ROOT / "docs" / "roadmap" / "PLANETARY_SCALE_PLAN.md"
PARKED_MD = ROOT / "docs" / "roadmap" / "PARKED.md"
GENERATED = "<!-- Generated by scripts/render_planetary_plan.py from docs/roadmap/planetary_streams.json; edit the JSON, not this file. -->"


def load() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def _stream_block(s: dict, heading: str = "###") -> list[str]:
    out = [f"{heading} {s['id']} — {s['title']}", ""]
    out += [f"**Objective.** {s['objective']}", "", f"**Why it matters.** {s['explanation']}", ""]
    meta = []
    meta.append("**Depends on:** " + (", ".join(s["dependencies"]) if s["dependencies"] else "nothing; can start now"))
    meta.append("**Pre-registration required:** " + ("yes, before any run" if s["prereg_required"] else "no"))
    meta.append("**Paper sections:** " + ", ".join(f"`{r}`" for r in s["paper_refs"]))
    meta.append("**Roadmap ids:** " + ", ".join(f"`{r}`" for r in s["roadmap_ids"]))
    meta.append("**Skills:** " + s["skills"])
    out += [m + "  " for m in meta] + [""]
    out += ["**Directions**", ""] + [f"{i}. {d}" for i, d in enumerate(s["directions"], 1)] + [""]
    out += ["**Definition of done**", ""] + [f"- [ ] `{d['id']}` {d['item']}" for d in s["definition_of_done"]] + [""]
    out += ["**Validation tests**", "", "| DoD | Command | Receipt | Passes when | Tool exists |", "|---|---|---|---|---|"]
    for v in s["validation"]:
        cmd = v["command"].replace("|", "\\|")
        out.append(f"| `{v['dod']}` | `{cmd}` | `{v['receipt']}` | {v['pass']} | {'yes' if v['exists'] else 'to be written'} |")
    out.append("")
    if s["constraints"]:
        out += ["**Constraints:** " + "; ".join(s["constraints"]) + ".", ""]
    if s["owner_decisions"]:
        out += ["**Owner decisions needed:** " + "; ".join(s["owner_decisions"]), ""]
    return out


def render_plan(m: dict) -> str:
    p = m["source_paper"]
    L = [GENERATED, "", f"# {m['plan']}", "",
         f"Derived from the foundation paper *{p['title']}*, version {p['version']} ([doi:{p['doi']}](https://doi.org/{p['doi']})), on {m['version']}.", "",
         "## 1. Where we are going", "", f"**{m['end_state']['name']}:** {m['end_state']['definition']}", "",
         f"*Source:* {m['end_state']['paper_source']}", "", "*Measured by:*", ""]
    L += [f"- {x}" for x in m["end_state"]["measured_by"]] + [""]
    L += ["## 2. Where we are (baseline, from receipts)", "", "| Fact | Receipt |", "|---|---|"]
    L += [f"| {f['fact']} | `{f['receipt']}` |" if f["receipt"].startswith(("artifacts/", "paper/")) else f"| {f['fact']} | {f['receipt']} |" for f in m["baseline"]["facts"]]
    L += ["", "## 3. Rules every stream follows", ""] + [f"{i}. {r}" for i, r in enumerate(m["rules"], 1)] + [""]
    L += ["## 4. Waves: entered on receipts, never on forecasts", "", "| Wave | Name | Node target | Status | Entry criteria (all required) |", "|---|---|---:|---|---|"]
    for w in m["waves"]:
        L.append(f"| {w['id']} | {w['name']} | {w['nodes_target']:,} | {w['status']} | " + "<br>".join(w["entry"]) + " |")
    L += ["", "## 5. Streams at a glance", "", "Ordered by dependency. A stream with no dependency can start today.", "",
          "| Stream | Title | Depends on | Pre-reg | Labels |", "|---|---|---|---|---|"]
    for s in m["streams"]:
        L.append(f"| [{s['id']}](#{s['id'].lower()}--{_slug(s['title'])}) | {s['title']} | {', '.join(s['dependencies']) or '—'} | {'yes' if s['prereg_required'] else 'no'} | {', '.join(s['labels'])} |")
    L += ["", "```mermaid", "graph LR"]
    for s in m["streams"]:
        L.append(f"  {s['id'].replace('-', '')}[\"{s['id']}: {s['title']}\"]")
        for d in s["dependencies"]:
            L.append(f"  {d.replace('-', '')} --> {s['id'].replace('-', '')}")
    L += ["```", "", "## 6. How to contribute", "",
          "1. Pick a stream whose dependencies are done (or which has none). Comment on its tracking issue to say what you take, so two people do not take the same item.",
          "2. If the stream needs pre-registration, open a PR with the pre-registration file first; nothing runs before it is merged.",
          "3. Each definition-of-done item is closed by its validation entry: run the command, commit the receipt, quote the pass condition in the PR.",
          "4. Run `uv run pytest` on what you touched; every PR passes the security scanner and the core checks.",
          "5. Never claim more than the receipt shows. A refuted result is a result.", "",
          "## 7. Streams in detail", ""]
    for s in m["streams"]:
        L += _stream_block(s)
    L += ["## 8. Parked ideas", "", "See [PARKED.md](PARKED.md): assessed ideas with the measured reason and the condition that would reopen them.", ""]
    return "\n".join(L)


def _slug(t: str) -> str:
    return "".join(c if c.isalnum() or c == " " or c == "-" else "" for c in t.lower()).strip().replace(" ", "-")


def render_parked(m: dict) -> str:
    L = [GENERATED, "", "# Parked ideas", "", "Assessed, measured and parked. Each entry names its receipt and the condition that would reopen it.", "",
         "| Idea | Decision | Measured reason | Receipt | Paper | Reopen if |", "|---|---|---|---|---|---|"]
    for p in m["parked"]:
        L.append(f"| {p['idea']} | `{p['decision']}` | {p['reason']} | `{p['receipt']}` | `{p['paper_ref']}` | {p['reopen_if']} |")
    return "\n".join(L) + "\n"


def render_issue(m: dict, sid: str) -> str:
    s = next(x for x in m["streams"] if x["id"] == sid)
    L = [f"Part of the planetary-scale plan (`docs/roadmap/PLANETARY_SCALE_PLAN.md`), derived from paper v{m['source_paper']['version']} (doi:{m['source_paper']['doi']}).", ""]
    L += _stream_block(s, heading="##")[2:]
    L += ["## How to take part", "",
          "Comment here with the definition-of-done item you take. Open one PR per item; quote the validation command and its receipt in the PR. "
          "If this stream needs pre-registration, the pre-registration PR comes first.", "",
          "*Generated from `docs/roadmap/planetary_streams.json`; the JSON is the source of truth.*"]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--issue")
    a = ap.parse_args()
    m = load()
    if a.issue:
        print(render_issue(m, a.issue))
        return 0
    plan, parked = render_plan(m) + "\n", render_parked(m)
    if a.check:
        ok = PLAN_MD.exists() and PLAN_MD.read_text(encoding="utf-8") == plan and PARKED_MD.exists() and PARKED_MD.read_text(encoding="utf-8") == parked
        print("in sync" if ok else "OUT OF SYNC: run scripts/render_planetary_plan.py")
        return 0 if ok else 1
    PLAN_MD.write_text(plan, encoding="utf-8")
    PARKED_MD.write_text(parked, encoding="utf-8")
    print(f"wrote {PLAN_MD.relative_to(ROOT)} and {PARKED_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
