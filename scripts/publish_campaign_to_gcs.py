def stage(stage_dir: Path, include_adapter: bool = False) -> Path:
    out = stage_dir / PKG
    SCRUBBED.clear()
    if out.exists():
        shutil.rmtree(out)
    skipped: List[str] = []
    for pat in REPORT_GLOBS:
        for f in sorted(EXP.glob(pat)):
            copy(f, out / "reports" / f.name, skipped)
    for sub in ("E15", "E16"):
        for f in sorted((EXP / sub).rglob("*")) if (EXP / sub).is_dir() else []:
            copy(f, out / "details" / sub / f.relative_to(EXP / sub), skipped)
    lora = Path(SCRATCH_LORA)
    if include_adapter and lora.is_file():
        (out / "adapters").mkdir(parents=True, exist_ok=True)
        shutil.copy2(lora, out / "adapters" / lora.name)
        (out / "adapters" / "README.md").write_text(
            f"E15 LoRA adapter (rank 16, alpha 32, all linear layers of Qwen/Qwen2.5-Coder-1.5B-Instruct), sha256 `{sha256(lora)}`.\n\n"
            "Trained on 673 GWAYA-gated (audit clean + all tests pass) self-generated solutions for 129 steps. Result: greedy MBPP-sanitized pass@1 "
            "+0.8 points over the base (p = 0.85): H15a is NOT supported; the GWAYA inference loop, not the adapter, produced the gain. "
            "Load with the hand-rolled LoRALinear of `scripts/e13_swarm_lib.py` / `scripts/e15_lib.py` (no `peft` needed).\n", encoding="utf-8")
    for f in sorted((ROOT / "docs" / "site").rglob("*")):
        copy(f, out / "site" / f.relative_to(ROOT / "docs" / "site"), skipped)
    for name in ("community/SWARM_LAB.md", "community/GWAYA_CODING_ASSISTANT.md", "community/GWAYA_T4_DEPLOYMENT.md", "community/GWAYA_LITE_ASSISTANT.md"):
        copy(ROOT / "docs" / name, out / "docs" / Path(name).name, skipped)
    copy(ROOT / "docs" / "benchmarks" / "T4_10h_campaign_report.md", out / "benchmarks" / "T4_10h_campaign_report.md", skipped)
    # runnable GWAYA-Lite assistant (stdlib only; the vendored GWAYA auditor keeps its MIT licence and provenance file)
    for rel in ("scripts/gwaya_lite.py", "scripts/e15_gate.py", "scripts/e15_data.py", "scripts/e16_ollama.py", "scripts/gwaya_lite_live_check.py",
                "third_party/gwaya/ast_audit.py", "third_party/gwaya/LICENSE", "third_party/gwaya/PROVENANCE.md"):
        copy(ROOT / rel, out / "code" / rel, skipped)
    (out / "code" / "README.md").write_text(
        "# GWAYA-Lite assistant (runnable bundle)\n\nRequires Python 3.10+, a local Ollama with `qwen2.5-coder:1.5b`, `qwen2.5-coder:3b`, `qwen2.5-coder:7b-instruct` "
        "and Linux user namespaces (`unshare`). No pip packages.\n\n```\ncd code\npython3 scripts/gwaya_lite.py doctor\npython3 scripts/gwaya_lite.py ask \"Write ...\" --test \"assert f(1) == 2\"\n"
        "python3 scripts/gwaya_lite.py serve --port 8099   # localhost only\n```\n\nVERIFIED means audit clean and your tests passed in the sandbox, never 'correct' "
        "(5-7% of VERIFIED solutions failed hidden tests in the T4 measurement). The sandbox is not GWAYA's Bubblewrap oracle and has no seccomp. "
        "`third_party/gwaya/` is the unmodified GWAYA zero-stub auditor (MIT, see LICENSE and PROVENANCE.md).\n", encoding="utf-8")
    (out / "GWAYA_PR21_P1_RESULTS.md").write_text(p1_results_md(), encoding="utf-8")
    (out / "README.md").write_text(
        f"# HiveMind T4 campaign package ({PKG})\n\nBuilt {time.strftime('%Y-%m-%d %H:%M:%S', time.gmtime())} UTC from branch "
        f"`{subprocess.run(['git', 'rev-parse', '--abbrev-ref', 'HEAD'], cwd=ROOT, capture_output=True, text=True).stdout.strip()}` at "
        f"`{subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], cwd=ROOT, capture_output=True, text=True).stdout.strip()}`.\n\n"
        "Experiments E10b, E11, E12, E13 (+c/d), E14, E15 (GWAYA-gated coding assistant) and E16 (GWAYA-Lite on a T4), all pre-registered; refuted and invalid outcomes are reported "
        "as such. No peer review of record exists. PTS / $HIVE carry no cash value. See `benchmarks/T4_10h_campaign_report.md`, `reports/` (receipts), "
        "`GWAYA_PR21_P1_RESULTS.md`, `docs/`. `MANIFEST.json` lists the sha256 of every file.\n", encoding="utf-8")
    files: Dict[str, str] = {str(f.relative_to(out)): sha256(f) for f in sorted(out.rglob("*")) if f.is_file() and f.name != "MANIFEST.json"}
    (out / "MANIFEST.json").write_text(json.dumps({"package": PKG, "files": files, "skipped_secret_like_or_denied": skipped, "username_scrubbed_in": sorted(set(SCRUBBED))}, indent=1, sort_keys=True), encoding="utf-8")
    print(json.dumps({"staged": str(out), "files": len(files), "bytes": sum(f.stat().st_size for f in out.rglob('*') if f.is_file()), "skipped": skipped, "username_scrubbed_in": sorted(set(SCRUBBED))}, indent=1))
    return out


def gcloud(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["gcloud", *args], capture_output=True, text=True)


def upload(out: Path, dest: str, allow_public: bool, allow_existing: bool) -> int:
    m = re.fullmatch(r"gs://([a-z0-9._-]+)/(.+?)/?", dest)
    if not m:
        print("destination must look like gs://BUCKET/PREFIX")
        return 2
    bucket, prefix = m.group(1), m.group(2)
    iam = gcloud("storage", "buckets", "get-iam-policy", f"gs://{bucket}", "--format=json")
    if iam.returncode != 0:
        print("cannot read the bucket IAM policy; refusing:", iam.stderr.strip()[:200])
        return 2
    public = bool(re.search(r"allUsers|allAuthenticatedUsers", iam.stdout))
    if public and not allow_public:
        print(f"REFUSED: gs://{bucket} has a public IAM binding (allUsers/allAuthenticatedUsers): every object uploaded would be world-readable. "
              "Use a private bucket, or pass --allow-public to publish deliberately.")
        return 3
    existing = gcloud("storage", "ls", f"gs://{bucket}/{prefix}/")
    if existing.returncode == 0 and existing.stdout.strip() and not allow_existing:
        print(f"REFUSED: gs://{bucket}/{prefix}/ already contains objects; pass --allow-existing to add to it.")
        return 3
    r = gcloud("storage", "cp", "-r", str(out) + "/*", f"gs://{bucket}/{prefix}/")
    print(r.stdout[-1500:], r.stderr[-1500:])
    return r.returncode


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", action="store_true")
    ap.add_argument("--stage-dir", default=DEFAULT_STAGE)
    ap.add_argument("--upload", default=None, help="gs://BUCKET/PREFIX")
    ap.add_argument("--include-adapter", action="store_true", help="also stage the 74 MB E15 LoRA adapter (excluded by default: no accuracy gain, and public downloads cost egress)")
    ap.add_argument("--allow-public", action="store_true")
    ap.add_argument("--allow-existing", action="store_true")
    a = ap.parse_args()
    if not (a.stage or a.upload):
        ap.error("--stage and/or --upload")
    out = stage(Path(a.stage_dir), a.include_adapter) if a.stage else Path(a.stage_dir) / PKG
    if a.upload:
        if not out.is_dir():
            print("nothing staged; run with --stage first")
            return 2
        return upload(out, a.upload, a.allow_public, a.allow_existing)
    return 0


if __name__ == "__main__":
    sys.exit(main())
