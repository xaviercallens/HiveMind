SCRATCH_LORA = "/mnt/disks/disk-socrateai-local-1/e15_scratch/E15_lora.pt"
DENY_NAME = ("token", "secret", "credential", "passwd", "password", ".env", "id_ed25519", "id_rsa", "apikey", "api_key", ".pem", ".key")
SECRET_RE = re.compile(rb"(gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|hf_[A-Za-z0-9]{25,}|AIza[0-9A-Za-z_\-]{30,}|-----BEGIN [A-Z ]*PRIVATE KEY-----|AKIA[0-9A-Z]{16}|xox[baprs]-[A-Za-z0-9-]{10,})")
REPORT_GLOBS = ("E1[0-6]*.json", "E1[0-6]*_prereg*.json", "E1[0-6]*_report*.json", "E13*.json", "E14*.json", "E15*.json", "E16*.json", "T4_benchmark_queue*.json",
                "predictions_ledger.json")


SCRUBBED: List[str] = []


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def safe(p: Path) -> bool:
    n = p.name.lower()
    if any(k in n for k in DENY_NAME):
        return False
    if p.suffix in (".json", ".jsonl", ".md", ".py", ".js", ".html", ".css", ".txt", ".tex"):
        return not SECRET_RE.search(p.read_bytes())
    return True


def copy(src: Path, dst: Path, skipped: List[str]) -> None:
    if not src.is_file():
        return
    if not safe(src):
        skipped.append(str(src.relative_to(ROOT)) if str(src).startswith(str(ROOT)) else src.name)
        return
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src.suffix in (".json", ".jsonl", ".md", ".txt", ".log"):  # public copies must not carry the machine username (it is derived from the owner's email)
        text = src.read_text(encoding="utf-8")
        scrubbed = text.replace("/home/callensxavier_gmail_com", "/home/<user>").replace("callensxavier_gmail_com", "<user>")
        if scrubbed != text:
            SCRUBBED.append(str(dst.name))
        dst.write_text(scrubbed, encoding="utf-8")
        return
    shutil.copy2(src, dst)


