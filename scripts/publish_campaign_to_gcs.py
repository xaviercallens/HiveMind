    head = ("# GWAYA draft PR #21 - P1/P2 measured on a Tesla T4 (hermes-node1)\n\n"
            "Source: HiveMind experiment E16 (pre-registered in `reports/E16_gwaya_lite_t4_prereg.json`), Ollama 0.34.1, Q4_K_M, MBPP-sanitized n=257, "
            "gate = vendored GWAYA zero-stub auditor + a namespace sandbox (NOT GWAYA's Bubblewrap oracle). Numbers are copied from the report; "
            "nothing here was posted to the GWAYA repository or PR.\n\n")
    if not rep.exists():
        return head + "The E16 report does not exist yet; this file is regenerated by `scripts/publish_campaign_to_gcs.py --stage` once it does.\n"
    r = json.loads(rep.read_text(encoding="utf-8"))
