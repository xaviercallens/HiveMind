"""Stage the T4-campaign results as one package and (only on request) upload it to a Google Cloud Storage prefix.

Stage (default, local, private, no cloud calls): builds ``<stage-dir>/t4_campaign_2026-10-24/`` with
  reports/   top-level campaign reports, predictions, pre-registrations and amendments (artifacts/experiments/*.json of E10b..E16, queue logs)
  details/   the git-ignored stage files and per-problem journals of E15 / E16 (artifacts/experiments/E15, E16)
  adapters/  (only with --include-adapter) the E15 LoRA adapter with its sha256 and a loading note (it did NOT improve greedy accuracy: H15a not supported)
  site/      the static Swarm Lab site (docs/site)
  docs/      community guides (Swarm Lab, GWAYA coding assistant, GWAYA T4 deployment)
  benchmarks/ the 10-hour campaign report
  GWAYA_PR21_P1_RESULTS.md  measured T4 numbers for GWAYA draft PR #21 (P1/P2), generated from the E16 report when it exists
  README.md, MANIFEST.json (sha256 of every file)
Excluded on purpose: the checkpoint archive and memory notes (internal plan, session names), job logs, anything matching the secret denylist/scan.

Upload (``--upload gs://bucket/prefix``): refuses unless the bucket IAM has NO ``allUsers`` / ``allAuthenticatedUsers`` binding; a public bucket needs
``--allow-public`` (publishing to the internet is irreversible once copied), and the prefix must not already contain objects unless ``--allow-existing``.
Objects are written with ``gcloud storage cp`` using the VM's own credentials; no ACLs are changed; nothing outside the prefix is touched.

    python3 scripts/publish_campaign_to_gcs.py --stage                      # local only
    python3 scripts/publish_campaign_to_gcs.py --stage --upload gs://BUCKET/PREFIX   # private bucket
"""

