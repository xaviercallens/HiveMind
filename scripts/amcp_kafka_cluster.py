"""A self-run Kafka cluster: three voters (quorum) plus optional broker-only nodes: configuration generator, and a local harness to prove it before any real host is touched.

Every node is a KRaft "combined" node (broker AND controller). Three controllers form the quorum; a majority (2 of 3) must be up for the cluster to accept writes, so ONE
node may be down. Topics use replication factor 3 and ``min.insync.replicas=2``, so an acknowledged write exists on at least two nodes.

  python scripts/amcp_kafka_cluster.py gen --node 1=10.77.0.1 --node 2=10.77.0.2 --node 3=10.77.0.3 --out ./cluster     # config for the real hosts
  python scripts/amcp_kafka_cluster.py local up --dir /tmp/k3                                                          # three nodes on this machine
  python scripts/amcp_kafka_cluster.py local stop-node 3 --dir /tmp/k3                                                 # then check the cluster still takes writes
  python scripts/amcp_kafka_cluster.py local down --dir /tmp/k3

Static quorum: Kafka 3.8 cannot add or remove controllers online (dynamic membership arrived in later releases), so the voter list is decided up front and every node
must carry the same list and the same cluster id. A node that is down is simply a voter that is not answering.
There is no authentication here. The listeners bind to the address given for each node, which is meant to be a private overlay address (WireGuard) or a VPC address,
never a public one.
"""

from __future__ import annotations

import argparse
import json
import os
import signal
import socket
import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path

DEFAULT_KAFKA_HOME = "/mnt/disks/disk-socrateai-local-1/amcp/tools/kafka"
DEFAULT_JAVA_HOME = "/mnt/disks/disk-socrateai-local-1/amcp/tools/jdk21"
BROKER_PORT, CONTROLLER_PORT = 9092, 9093


@dataclass(frozen=True)
class Node:
    node_id: int
    host: str  # the address the OTHER nodes and the clients use for this node
    broker_port: int = BROKER_PORT
    controller_port: int = CONTROLLER_PORT
    voter: bool = True  # False: a broker-only node (stores and serves partitions, takes no part in the controller vote); can join at any time


class ClusterError(ValueError):
    pass


def quorum_size(voters: int) -> int:
    return voters // 2 + 1


def tolerated_failures(voters: int) -> int:
    return voters - quorum_size(voters)


def voters_of(nodes: list[Node]) -> list[Node]:
    return [n for n in nodes if n.voter]


def validate(nodes: list[Node], replication: int, min_isr: int) -> None:
    n_voters = len(voters_of(nodes))
    if n_voters < 3 or n_voters % 2 == 0:
        raise ClusterError(f"a quorum needs an odd number of voters, at least 3 (got {n_voters}): 4 voters tolerate no more failures than 3")
    if len({n.node_id for n in nodes}) != len(nodes) or any(n.node_id < 1 for n in nodes):
        raise ClusterError("node ids must be unique positive integers")
    endpoints = [(n.host, p) for n in nodes for p in ((n.broker_port, n.controller_port) if n.voter else (n.broker_port,))]
    if len(set(endpoints)) != len(endpoints):
        raise ClusterError("two listeners share the same host and port")
    if not 1 <= min_isr <= replication <= len(nodes):
        raise ClusterError("need 1 <= min_isr <= replication <= number of nodes")
    if min_isr < quorum_size(replication):
        raise ClusterError(f"min.insync.replicas={min_isr} is below a majority of replication {replication}: an acknowledged write could be lost with one failure")


def node_properties(node: Node, nodes: list[Node], data_dir: str, *, replication: int = 3, min_isr: int = 2, retention_hours: int = 168) -> str:
    validate(nodes, replication, min_isr)
    voters = ",".join(f"{n.node_id}@{n.host}:{n.controller_port}" for n in voters_of(nodes))
    return "\n".join([
        "# Generated by scripts/amcp_kafka_cluster.py. Same voters and same cluster id on every node. No authentication: bind to a private address only.",
        f"process.roles={'broker,controller' if node.voter else 'broker'}",
        f"node.id={node.node_id}",
        f"controller.quorum.voters={voters}",
        f"listeners=BROKER://{node.host}:{node.broker_port}" + (f",CONTROLLER://{node.host}:{node.controller_port}" if node.voter else ""),
        f"advertised.listeners=BROKER://{node.host}:{node.broker_port}",
        "inter.broker.listener.name=BROKER",
        "controller.listener.names=CONTROLLER",
        "listener.security.protocol.map=BROKER:PLAINTEXT,CONTROLLER:PLAINTEXT",
        f"log.dirs={data_dir}",
        "num.partitions=3",
        f"default.replication.factor={replication}",
        f"min.insync.replicas={min_isr}",
        f"offsets.topic.replication.factor={replication}",
        "offsets.topic.num.partitions=12",
        f"transaction.state.log.replication.factor={replication}",
        f"transaction.state.log.min.isr={min_isr}",
        "unclean.leader.election.enable=false",
        "auto.create.topics.enable=false",
        "group.initial.rebalance.delay.ms=0",
        # Measured on the local three-node test: with the default 60 s a node that cannot reach a majority of voters SHUTS DOWN ("unable to register with the
        # controller quorum") instead of waiting. On a cluster where peers are Spot or home machines that would make every restart race its peers. Wait up to 10 min.
        "initial.broker.registration.timeout.ms=600000",
        f"log.retention.hours={retention_hours}",
        "",
    ])


def parse_node(text: str, voter: bool = True) -> Node:
    ident, _, host = text.partition("=")
    if not ident.isdigit() or not host:
        raise argparse.ArgumentTypeError("--node expects ID=HOST, for example 1=10.77.0.1")
    return Node(int(ident), host, voter=voter)


def parse_broker(text: str) -> Node:
    return parse_node(text, voter=False)


def cmd_gen(args: argparse.Namespace) -> int:
    nodes = sorted(args.node + (args.broker or []), key=lambda n: n.node_id)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for n in nodes:
        (out / f"node{n.node_id}.properties").write_text(node_properties(n, nodes, args.data_dir, replication=args.replication, min_isr=args.min_isr))
    print(json.dumps({"written": [f"node{n.node_id}.properties" for n in nodes], "voters": len(voters_of(nodes)), "brokers": len(nodes), "quorum": quorum_size(len(voters_of(nodes))),
                      "tolerated_voter_failures": tolerated_failures(len(voters_of(nodes))), "topic_replication": args.replication, "topic_min_isr": args.min_isr,
                      "tolerated_replica_failures_per_partition": args.replication - args.min_isr,
                      "next": "on EACH node: kafka-storage.sh format -t <ONE shared cluster id> -c nodeN.properties, then kafka-server-start.sh nodeN.properties"}, indent=2))
    return 0


# --------------------------------------------------------------------------------------------------------------------------------------
# local harness: three real broker processes on loopback ports, to prove quorum behaviour on this machine first
# --------------------------------------------------------------------------------------------------------------------------------------


def local_nodes(total: int = 3, voters: int = 3) -> list[Node]:
    return [Node(i, "127.0.0.1", 29092 + 100 * (i - 1), 29093 + 100 * (i - 1), voter=i <= voters) for i in range(1, total + 1)]


def env_for(args: argparse.Namespace) -> dict[str, str]:
    return dict(os.environ, JAVA_HOME=args.java_home, KAFKA_HEAP_OPTS="-Xms128m -Xmx256m", LOG_DIR=str(Path(args.dir) / "logs"))


def listening(port: int) -> bool:
    with socket.socket() as s:
        s.settimeout(0.5)
        return s.connect_ex(("127.0.0.1", port)) == 0


def spawn_node(args: argparse.Namespace, n: Node) -> None:
    base = Path(args.dir)
    pidfile = base / f"node{n.node_id}.pid"
    if pidfile.exists() and _alive(int(pidfile.read_text())):
        return
    proc = subprocess.Popen([f"{args.kafka_home}/bin/kafka-server-start.sh", str(base / f"node{n.node_id}.properties")], env=env_for(args), start_new_session=True,
                            stdout=open(base / f"node{n.node_id}.out", "ab"), stderr=subprocess.STDOUT)
    pidfile.write_text(str(proc.pid))


def wait_listening(args: argparse.Namespace, nodes: list[Node], timeout_s: float = 120.0) -> None:
    """A node of a 3-voter quorum only finishes starting once a MAJORITY is up, so start them all first and wait afterwards."""
    deadline = time.time() + timeout_s
    pending = list(nodes)
    while pending and time.time() < deadline:
        pending = [n for n in pending if not listening(n.broker_port)]
        time.sleep(0.5)
    if pending:
        raise SystemExit(f"node(s) {[n.node_id for n in pending]} did not start listening; see {args.dir}/nodeN.out")


def _alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
        return Path(f"/proc/{pid}").exists() and Path(f"/proc/{pid}/stat").read_text().split()[2] != "Z"
    except OSError:
        return False


def stop_node(args: argparse.Namespace, node_id: int) -> None:
    pidfile = Path(args.dir) / f"node{node_id}.pid"
    if not pidfile.exists():
        return
    pid = int(pidfile.read_text())
    if _alive(pid):
        os.killpg(os.getpgid(pid), signal.SIGTERM)
        deadline = time.time() + 60
        while time.time() < deadline and _alive(pid):
            time.sleep(0.5)
        if _alive(pid):
            os.killpg(os.getpgid(pid), signal.SIGKILL)
    pidfile.unlink(missing_ok=True)


def cmd_local(args: argparse.Namespace) -> int:
    base = Path(args.dir)
    nodes = local_nodes(args.total, args.voters)
    if args.action == "up":
        base.mkdir(parents=True, exist_ok=True)
        (base / "logs").mkdir(exist_ok=True)
        cluster_id = (base / "cluster_id").read_text().strip() if (base / "cluster_id").exists() else subprocess.run(
            [f"{args.kafka_home}/bin/kafka-storage.sh", "random-uuid"], env=env_for(args), capture_output=True, text=True, check=True).stdout.strip()
        (base / "cluster_id").write_text(cluster_id)
        for n in nodes:
            cfg = base / f"node{n.node_id}.properties"
            cfg.write_text(node_properties(n, nodes, str(base / f"data{n.node_id}"), replication=args.replication, min_isr=args.min_isr))
            if not (base / f"data{n.node_id}" / "meta.properties").exists():
                subprocess.run([f"{args.kafka_home}/bin/kafka-storage.sh", "format", "-t", cluster_id, "-c", str(cfg)], env=env_for(args), check=True, capture_output=True)
        for n in nodes:
            spawn_node(args, n)
        wait_listening(args, nodes)
        print(json.dumps({"voters": args.voters, "up": [n.node_id for n in nodes], "bootstrap": ",".join(f"127.0.0.1:{n.broker_port}" for n in nodes), "cluster_id": cluster_id}))
    elif args.action == "stop-node":
        stop_node(args, args.node_id)
        print(json.dumps({"stopped": args.node_id}))
    elif args.action == "start-node":
        spawn_node(args, nodes[args.node_id - 1])
        wait_listening(args, [nodes[args.node_id - 1]])
        print(json.dumps({"started": args.node_id}))
    elif args.action == "down":
        for n in nodes:
            stop_node(args, n.node_id)
        print(json.dumps({"down": True}))
    elif args.action == "status":
        print(json.dumps({f"node{n.node_id}": {"broker": listening(n.broker_port), "controller": listening(n.controller_port) if n.voter else None} for n in nodes}))
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen", help="write one server.properties per node")
    g.add_argument("--node", action="append", type=parse_node, required=True, help="a VOTER (broker + controller), ID=HOST; repeat, odd count >= 3")
    g.add_argument("--broker", action="append", type=parse_broker, help="a broker-only node, ID=HOST; may be added at any time, takes no part in the controller vote")
    g.add_argument("--out", required=True)
    g.add_argument("--data-dir", default="/var/lib/hivemind-kafka")
    g.add_argument("--replication", type=int, default=3)
    g.add_argument("--min-isr", type=int, default=2)
    loc = sub.add_parser("local", help="run three nodes on loopback ports 29092/29192/29292 (a test harness, not a deployment)")
    loc.add_argument("action", choices=["up", "down", "status", "stop-node", "start-node"])
    loc.add_argument("node_id", nargs="?", type=int)
    loc.add_argument("--replication", type=int, default=3, help="replication factor of the internal topics (and the default for new ones)")
    loc.add_argument("--min-isr", type=int, default=2)
    loc.add_argument("--total", type=int, default=3, help="number of local nodes")
    loc.add_argument("--voters", type=int, default=3, help="how many of them (ids 1..N) are voters; the rest are broker-only")
    loc.add_argument("--dir", required=True)
    loc.add_argument("--kafka-home", default=os.environ.get("HIVEMIND_KAFKA_HOME", DEFAULT_KAFKA_HOME))
    loc.add_argument("--java-home", default=os.environ.get("JAVA_HOME_21", DEFAULT_JAVA_HOME))
    args = ap.parse_args(argv)
    try:
        if args.cmd == "gen":
            return cmd_gen(args)
        if args.action in ("stop-node", "start-node") and args.node_id is None:
            ap.error(f"{args.action} needs a node id")
        return cmd_local(args)
    except ClusterError as exc:
        print(f"refused: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
